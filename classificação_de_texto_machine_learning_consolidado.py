# ============================================================
# TREINAMENTO E AVALIAÇÃO DOS 3 MODELOS
# ============================================================

# Instanciação dos três classificadores com tratamento de desbalanceamento
modelos = {
    "Multinomial Naive Bayes": MultinomialNB(fit_prior=False),
    "Random Forest": RandomForestClassifier(class_weight='balanced', random_state=42),
    "Linear SVM": LinearSVC(class_weight='balanced', random_state=42)
}

# Lista para armazenar métricas para a tabela comparativa
resultados = []

def show_confusion_matrix(cm, titulo):
    plt.figure(figsize=(5, 4))
    hmap = sns.heatmap(cm, annot=True, fmt="d", cmap="Blues", cbar=False)
    hmap.yaxis.set_ticklabels(['Não Ódio (0)', 'Com Ódio (1)'], rotation=0, ha='right')
    hmap.xaxis.set_ticklabels(['Não Ódio (0)', 'Com Ódio (1)'], rotation=30, ha='right')
    plt.ylabel('Classe Real')
    plt.xlabel('Classe Predita')
    plt.title(f'Matriz de Confusão: {titulo}', fontweight='bold')
    plt.show()

"""#### **Testando os modelos de Machine Learning**"""

# AVALIAÇÃO COMPARATIVA DOS MODELOS

for nome, modelo in modelos.items():
    # 1. Treinamento
    modelo.fit(train_df, train_label)

    # 2. Predição
    pred = modelo.predict(test_df)

    # 3. Matriz de Confusão
    cm = confusion_matrix(test_label, pred)
    show_confusion_matrix(cm, nome)

    # 4. Relatório de Classificação no console
    print(f"--- RELATÓRIO DE DESEMPENHO: {nome} ---")
    print(classification_report(test_label, pred, target_names=['Não Ódio (0)', 'Com Ódio (1)']))
    print("-" * 60 + "\n")

    # 5. Cálculo das métricas para a classe de interesse (1 - Ódio)
    acc = accuracy_score(test_label, pred)
    prec = precision_score(test_label, pred, pos_label=1)
    rec = recall_score(test_label, pred, pos_label=1)
    f1 = f1_score(test_label, pred, pos_label=1)

    resultados.append({
        "Modelo": nome,
        "Acurácia Geral": f"{acc:.4f}",
        "Precisão (Ódio)": f"{prec:.4f}",
        "Recall (Ódio)": f"{rec:.4f}",
        "F1-Score (Ódio)": f"{f1:.4f}"
    })

# TABELA COMPARATIVA FINAL

df_comparativo = pd.DataFrame(resultados)
